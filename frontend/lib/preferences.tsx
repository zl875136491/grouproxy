function translate(locale: Locale, key: string, values?: Values) {
  // Backend enums use snake_case while message keys are human-readable. Try
  // both forms so a status/error can be translated without changing the API
  // payload or forcing a refetch when the locale changes.
  let message = messages[locale][key] || messages[locale][key.replaceAll("_", " ")] || key;
  for (const [name, value] of Object.entries(values || {})) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

type PreferencesContextValue = Formatters & {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  theme: Theme;
  setTheme: (theme: Theme) => void;
  t: (key: string, values?: Values) => string;
};

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

export function PreferencesProvider({ children }: PropsWithChildren) {
  const [locale, setLocale] = useState<Locale>("zh-CN");
  const [theme, setTheme] = useState<Theme>("light");

  useEffect(() => {
    const savedLocale = window.localStorage.getItem(localeStorageKey);
    const savedTheme = window.localStorage.getItem(themeStorageKey);
    if (savedLocale === "zh-CN" || savedLocale === "en" || savedLocale === "es") {
      setLocale(savedLocale);
    }
    if (savedTheme === "light" || savedTheme === "dark") {
      setTheme(savedTheme);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(localeStorageKey, locale);
  }, [locale]);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.style.colorScheme = theme;
    window.localStorage.setItem(themeStorageKey, theme);
  }, [theme]);

  const formatters = useMemo(() => createFormatters(locale), [locale]);
  const value = useMemo<PreferencesContextValue>(
    () => ({ ...formatters, locale, setLocale, theme, setTheme, t: (key, values) => translate(locale, key, values) }),
    [formatters, locale, theme],
  );

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error("usePreferences must be used within PreferencesProvider");
  return context;
}
